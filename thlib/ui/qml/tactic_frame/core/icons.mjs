export function ownValue(values, name) {
    return values && Object.prototype.hasOwnProperty.call(values, name)
        ? values[name]
        : undefined;
}

export function semanticName(source) {
    const name = String(source || '').replace(/_/g, '-');
    return ownValue(semanticAliases, name) || name;
}

export function resolve(source, pack, glyph, forceSolid = false) {
    if (!source) return null;
    const prefix = /^(FA|FAS|FAR|MDI)_(.+)$/i.exec(source);
    if (prefix) {
        let family = 'fontawesome-solid';
        if (prefix[1].toUpperCase() === 'MDI') family = 'material-design';
        else if (prefix[1].toUpperCase() === 'FAR')
            family = 'fontawesome-outline';
        return resolve(
            family + ':' + prefix[2].replace(/_/g, '-').toLowerCase(),
            pack,
            glyph,
            forceSolid
        );
    }
    const normalized = semanticName(source);
    const separator = normalized.indexOf(':');
    if (separator > 0) {
        const set = normalized.slice(0, separator),
            name = normalized.slice(separator + 1);
        return glyph(set, name) ? { set, name } : null;
    }
    const candidate = ownValue(aliases, normalized) || normalized;
    const fontAwesomeName =
        glyph('fontawesome-solid', candidate) ||
        glyph('fontawesome-outline', candidate)
            ? candidate
            : '';
    const direct = ownValue(materialAliases, normalized) || normalized;
    const mapped = ownValue(materialAliases, candidate) || candidate;
    const materialName = glyph('material-design', direct)
        ? direct
        : glyph('material-design', mapped)
          ? mapped
          : '';
    let missing = !fontAwesomeName;
    if (pack === 'material-design') missing = !materialName;
    else if (pack === 'automatic') missing = !fontAwesomeName && !materialName;
    let catalogSet = '';
    if (pack.startsWith('fluent-')) catalogSet = pack;
    else if (missing)
        catalogSet = forceSolid ? 'fluent-filled' : 'fluent-regular';
    const fluentName = ownValue(fluentAliases, normalized) || normalized;
    if (catalogSet && glyph(catalogSet, fluentName))
        return { set: catalogSet, name: fluentName };
    if (
        !forceSolid &&
        materialName &&
        (pack === 'material-design' || pack === 'automatic' || !fontAwesomeName)
    )
        return { set: 'material-design', name: materialName };
    if (!fontAwesomeName) return null;
    const name = fontAwesomeName;
    const regular = glyph('fontawesome-outline', name),
        solid = glyph('fontawesome-solid', name);
    const set =
        !forceSolid &&
        regular &&
        (pack === 'fontawesome-outline' ||
            (pack === 'automatic' && ownValue(automaticOutlineGlyphs, name)) ||
            !solid)
            ? 'fontawesome-outline'
            : 'fontawesome-solid';
    return glyph(set, name) ? { set, name } : null;
}
