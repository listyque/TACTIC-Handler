"""Declarative inputs for project provisioning, shared by HTTP and MCP boundaries."""
import re
from typing import Annotated, Literal

from pydantic import BaseModel, ConfigDict, Field, model_validator

Code = Annotated[str, Field(pattern=r'^[a-z][a-z0-9_]{0,29}$')]
Label = Annotated[str, Field(min_length=1, max_length=100)]


class PlanValue(BaseModel):
    model_config = ConfigDict(extra='forbid', strict=True)


class Column(PlanValue):
    name: Code
    type: Literal['varchar(256)', 'text', 'integer', 'numeric', 'boolean', 'timestamp'] = 'varchar(256)'


class Entity(PlanValue):
    code: Code
    title: Label
    description: Annotated[str, Field(max_length=2000)] = ''
    columns: Annotated[list[Column], Field(max_length=61)] = Field(default_factory=list)


class Relation(PlanValue):
    source: Code
    target: Code
    source_column: Code
    # A link entity with two code connections is the native many-to-many contract.
    instance: Code | None = None
    target_column: Code | None = None


class Pipeline(PlanValue):
    entity: Code
    processes: Annotated[list[Label], Field(min_length=1, max_length=64)]
    connections: Annotated[list[Annotated[list[str], Field(min_length=2, max_length=2)]], Field(max_length=128)] = Field(default_factory=list)
    statuses: Annotated[list[Label], Field(max_length=32)] = Field(default_factory=list)


class Naming(PlanValue):
    entity: Code
    context: Annotated[str, Field(max_length=256)] = ''
    dir_naming: Annotated[str, Field(min_length=1, max_length=1024)]
    file_naming: Annotated[str, Field(min_length=1, max_length=256)]
    checkin_type: Literal['auto', 'strict'] = 'strict'


class ProjectPlan(PlanValue):
    code: Code
    title: Label
    description: Annotated[str, Field(max_length=2000)] = ''
    entities: Annotated[list[Entity], Field(min_length=1, max_length=32)]
    relations: Annotated[list[Relation], Field(max_length=64)] = Field(default_factory=list)
    pipelines: Annotated[list[Pipeline], Field(max_length=32)] = Field(default_factory=list)
    naming: Annotated[list[Naming], Field(max_length=64)] = Field(default_factory=list)

    @model_validator(mode='after')
    def references(self):
        def unique(values, label):
            if len(values) != len(set(values)):
                raise ValueError('Duplicate ' + label)
        unique([item.code for item in self.entities], 'entity')
        entities = {item.code: item for item in self.entities}
        labels = [self.title] + [item.title for item in self.entities]
        labels += [name for item in self.pipelines for name in item.processes + item.statuses]
        if any(not label.strip() for label in labels):
            raise ValueError('Titles, processes and statuses cannot be blank')
        reserved = {'id', 'code', 'name', 'description', 'keywords', 's_status', 'timestamp', 'login', 'pipeline_code', 'data', 'relative_dir'}
        for entity in self.entities:
            unique([column.name for column in entity.columns], 'column')
            if any(column.name in reserved for column in entity.columns):
                raise ValueError('TACTIC provides standard columns; omit them from additions')
        instances = [edge.instance for edge in self.relations if edge.instance]
        unique(instances, 'instance entity')
        if set(instances) & entities.keys():
            raise ValueError('Instance entities are generated by the relationship editor')
        for edge in self.relations:
            if edge.source not in entities or edge.target not in entities:
                raise ValueError('Relationship refers to an unknown entity')
            if edge.instance and (not edge.target_column or edge.source_column == edge.target_column or edge.source == edge.target):
                raise ValueError('An instance needs two distinct entities and key columns')
            if not edge.instance and edge.target_column:
                raise ValueError('Ordinary relationships reference the target code column')
            if edge.source_column in reserved or edge.target_column in reserved:
                raise ValueError('Relationship keys cannot replace TACTIC standard columns')
        unique([item.entity for item in self.pipelines], 'entity pipeline')
        for pipeline in self.pipelines:
            if pipeline.entity not in entities:
                raise ValueError('Pipeline refers to an unknown entity')
            unique(pipeline.processes, 'process')
            unique(pipeline.statuses, 'status')
            for source, target in pipeline.connections:
                if source not in pipeline.processes or target not in pipeline.processes:
                    raise ValueError('Pipeline connection refers to an unknown process')
        unique([(item.entity, item.context) for item in self.naming], 'naming context')
        for rule in self.naming:
            if rule.entity not in entities:
                raise ValueError('Naming refers to an unknown entity')
            tokens = reserved | {column.name for column in entities[rule.entity].columns} | {
                'project.code', 'project.title', 'snapshot.version', 'snapshot.context',
                'snapshot.process', 'version', 'context', 'process', 'ext', 'basefile', 'file_type'}
            tokens |= {'sobject.' + field for field in reserved | {c.name for c in entities[rule.entity].columns}}
            for edge in self.relations:
                if edge.source == rule.entity and not edge.instance:
                    tokens |= {'parent.' + field for field in reserved | {c.name for c in entities[edge.target].columns}}
            for value in (rule.dir_naming, rule.file_naming):
                if any(char in value for char in ('@', '$', '<', '>', '\\', ':')):
                    raise ValueError('Project plans accept declarative naming tokens, not expressions or paths to programs')
                for token in re.findall(r'\{([^{}]*)\}', value):
                    base = re.sub(r'\[\d+\]$', '', token)
                    if base not in tokens and not re.fullmatch(r'#{1,9}', token):
                        raise ValueError('Unknown naming token: ' + token)
                literal = re.sub(r'\{[^{}]*\}', 'value', value)
                if '{' in literal or '}' in literal or literal.startswith('/') or '..' in literal.split('/'):
                    raise ValueError('Naming must be a relative path with balanced tokens')
            if '/' in rule.file_naming or rule.dir_naming.endswith('/'):
                raise ValueError('Use a directory without a trailing slash and a filename without directories')
        return self
